/**
 * The hero as HTML + CSS on the user's design system.
 *
 * Every value that should follow the brand is a token: the gradient stops are
 * --{Family}-Color-N, the text is --BW-Color-1 / -6 (the colors Omni assigns
 * to tones 1–5 and 6–12), the overlay is that same BW color mixed to the
 * solved opacity, and the type is the user's own styles (--Display-Medium-*,
 * --Body-Large-*, the Eyebrow). Only geometry and the solved opacity are
 * literal — they are the design.
 */
import { headlineWords, altStyleFor, type HeroSpec, type HeroRole } from './heroSpec';

const esc = (s: string) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export const toneToken = (family: string, tone: number) => `var(--${family}-Color-${Math.round(tone)})`;
const BW = { light: 'var(--BW-Color-1)', dark: 'var(--BW-Color-6)' };

/** A type style's tokens as declarations. */
const typeStyle = (style: string) => [
  `font-family: var(--${style}-Font-Family)`,
  `font-size: var(--${style}-Font-Size)`,
  `font-weight: var(--${style}-Font-Weight)`,
  `line-height: var(--${style}-Line-Height)`,
  `letter-spacing: var(--${style}-Letter-Spacing)`,
  `text-transform: var(--${style}-Text-Transform, none)`,
].join('; ');

