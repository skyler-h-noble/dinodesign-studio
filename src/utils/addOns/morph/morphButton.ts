/**
 * Morph Button — the add-on's state, its share link and the code it writes.
 *
 * The component is the lib's ShapeButton; this add-on is the place to choose
 * a pair that blends, the moment it morphs, and to get the code and the
 * Figma steps for it. Same way in as every other add-on: a link with the
 * setup in #spec=, and the exported file carries that link, so either one
 * pasted into Import reopens it.
 */
import { encodeChartSpec, decodeChartSpec } from '../charts/chartShare';

export const MORPH_SHARE_VERSION = 'morph-button/1';
export type MorphTrigger = 'selected' | 'hover' | 'press';
export type MorphSize = 'small' | 'medium' | 'large';

export interface MorphState {
  version: typeof MORPH_SHARE_VERSION;
  shape: string;
  morphTo: string;
  morphOn: MorphTrigger;
  color: string;
  size: MorphSize;
  /** A Material icon name, e.g. Favorite. */
  icon: string;
  /** What pressing it does — its accessible name. */
  label: string;
}

export const DEFAULT_MORPH: MorphState = {
  version: MORPH_SHARE_VERSION,
  shape: 'circle',
  morphTo: 'cookie-9',
  morphOn: 'selected',
  color: 'primary',
  size: 'large',
  icon: 'Favorite',
  label: 'Add to favourites',
};

export const MORPH_ICONS = ['Favorite', 'Star', 'Bookmark', 'Add', 'PlayArrow', 'Check', 'ThumbUp', 'Notifications'];

export const encodeMorphState = (s: MorphState): string => encodeChartSpec(s);

/** The state in a link, a #spec= fragment, or the exported file — or null. */
export function readMorphState(text: string): MorphState | null {
  const m = text.match(/[#&]spec=([A-Za-z0-9_-]+)/);
  if (!m) return null;
  try {
    const s = decodeChartSpec(m[1]) as MorphState;
    return s && typeof s === 'object' && s.version === MORPH_SHARE_VERSION ? { ...DEFAULT_MORPH, ...s } : null;
  } catch {
    return null;
  }
}

/** One React file: the button, wired for its trigger. */
export function morphCode(s: MorphState, editLink?: string): string {
  const toggle = s.morphOn === 'selected';
  const props = [
    `shape="${s.shape}"`,
    `morphTo="${s.morphTo}"`,
    `morphOn="${s.morphOn}"`,
    ...(toggle ? ['selected={on}', 'onClick={() => setOn((v) => !v)}'] : ['onClick={onClick}']),
    ...(s.color !== 'primary' ? [`color="${s.color}"`] : []),
    ...(s.size !== 'medium' ? [`size="${s.size}"`] : []),
    `aria-label="${s.label.replace(/"/g, '&quot;')}"`,
  ];
  return [
    '/**',
    ' * MorphButton — generated by Omni Design (Morph Button add-on).',
    ` * ${s.shape} → ${s.morphTo}, ${s.morphOn === 'selected' ? 'while selected' : s.morphOn === 'hover' ? 'on hover' : 'while pressed'}.`,
    ...(editLink ? [' *', ' * Edit in the studio — open this link, or paste this file into Import:', ' * ' + editLink] : []),
    ' */',
    `import React${toggle ? ', { useState }' : ''} from 'react';`,
    "import { ShapeButton } from '@omni-design/components';",
    `import ${s.icon}Icon from '@mui/icons-material/${s.icon}';`,
    '',
    `export default function MorphButton(${toggle ? '' : '{ onClick }'}) {`,
    ...(toggle ? ['  const [on, setOn] = useState(false);'] : []),
    '  return (',
    '    <ShapeButton',
    ...props.map((p) => '      ' + p),
    '    >',
    `      <${s.icon}Icon />`,
    '    </ShapeButton>',
    '  );',
    '}',
    '',
  ].join('\n');
}
