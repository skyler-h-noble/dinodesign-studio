/**
 * A share image as HTML (for the preview and the PNG), and the meta tags that
 * point a page at it.
 *
 * The card is the hero's own HTML at a fixed size, inside a wrapper that sets
 * data-device="Desktop" and the desktop margin — a share image is drawn once,
 * at desktop size — plus the site name as the text block's last line, so the
 * contrast the hero solves for its text covers the site name too.
 */
import { heroHTML, heroHeadlineColor } from '../hero/heroCode';
import { svgDataUrl } from '../brand/brandSpec';
import { heroAtSize, SHARE_MARGIN, SHARE_SIZES, type ShareSpec, type ShareSize } from './shareSpec';

const esc = (s: string) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export const SHARE_CSS = `.omni-share { position: relative; overflow: hidden; box-sizing: border-box; }
.omni-share > .omni-hero { height: 100%; }
.omni-share__site {
  font-family: var(--Body-Large-Font-Family, var(--Body-Font-Family));
  font-size: var(--Body-Large-Font-Size, 18px);
  line-height: var(--Body-Large-Line-Height, 1.4);
  font-weight: var(--Body-Semibold-Font-Weight, 600);
  margin-top: var(--Sizing-2, 16px) !important;
}
/* The brand above the text: the one-color ink as a mask, in the headline's color. */
.omni-share__brand {
  display: block; flex: none; height: var(--omni-brand-height); aspect-ratio: var(--omni-brand-aspect);
  -webkit-mask: var(--omni-brand-src) center / contain no-repeat; mask: var(--omni-brand-src) center / contain no-repeat;
  margin-bottom: var(--Sizing-1, 8px) !important;
}`;

/** The design system's ink SVGs, when it has a saved brand. */
export interface ShareBrandInk { logo?: { svg: string; aspect: number } | null; stacked?: { svg: string; aspect: number } | null; mark?: { svg: string; aspect: number } | null; name?: string }

/** One size's card. `imageSrc` is the photo (the user's, or the sample). */
export function shareCardHTML(spec: ShareSpec, size: ShareSize, imageSrc: string, brand?: ShareBrandInk | null): string {
  const heroSpec = heroAtSize(spec, size);
  let hero = heroHTML(heroSpec, imageSrc);
  const ink = spec.brand !== 'none' && brand ? brand[spec.brand] : null;
  if (ink) {
    /* First in the text block, so the overlay solved for the text covers it,
       and in the headline's own color, which that solve checked. Logos are
       wider than marks, so a logo is drawn shorter. */
    const h = spec.brand === 'logo' ? 56 : spec.brand === 'stacked' ? 120 : 80;
    const mark = `
    <span class="omni-share__brand" role="img" aria-label="${esc(brand?.name || spec.siteName || 'Brand')}" style="--omni-brand-src: url('${svgDataUrl(ink.svg)}'); --omni-brand-aspect: ${Math.round(ink.aspect * 1000) / 1000}; --omni-brand-height: ${h}px; background: ${heroHeadlineColor(heroSpec)}"></span>`;
    const open = hero.indexOf('<div class="omni-hero__content"');
    const tagEnd = hero.indexOf('>', open) + 1;
    if (open >= 0) hero = hero.slice(0, tagEnd) + mark + hero.slice(tagEnd);
  }
  if (spec.siteName) {
    const site = `\n    <p class="omni-share__site">${esc(spec.siteName)}</p>`;
    const end = hero.lastIndexOf('\n  </div>\n</section>');
    if (end >= 0) hero = hero.slice(0, end) + site + hero.slice(end);
  }
  return `<div class="omni-share" data-device="Desktop" data-share="${size.key}" style="width: ${size.w}px; height: ${size.h}px; --Margin: ${SHARE_MARGIN}px">\n${hero}\n</div>`;
}

/**
 * The <head> tags for a page shared with these images. The wide card is the
 * Open Graph image every platform reads (X included, as summary_large_image);
 * with no wide card, the square becomes it and X shows a summary card. The
 * Pinterest image is not a meta tag: Pinterest reads it off the page, from
 * data-pin-media on an image.
 */
export function shareMetaTags(spec: ShareSpec): string {
  const sizes = SHARE_SIZES.filter((s) => spec.sizes.includes(s.key));
  const main = sizes.find((s) => s.key === 'og') || sizes.find((s) => s.key === 'square');
  const pin = sizes.find((s) => s.key === 'pinterest');
  const base = spec.page.imageBase.endsWith('/') ? spec.page.imageBase : spec.page.imageBase + '/';
  const t = spec.hero.text;
  const title = t.headline;
  const description = t.body;
  // The image's words are its content, so they are its description unless the user wrote one.
  const alt = spec.page.alt || [t.eyebrow, t.headline, spec.siteName].filter(Boolean).join(' — ');
  const m = (attr: 'property' | 'name', key: string, value: string) => `<meta ${attr}="${key}" content="${esc(value)}">`;
  const lines = ['<!-- Share image — generated by the Share Images add-on -->',
    m('property', 'og:type', 'website'),
    m('property', 'og:url', spec.page.url),
    ...(spec.siteName ? [m('property', 'og:site_name', spec.siteName)] : []),
    m('property', 'og:title', title),
    ...(description ? [m('property', 'og:description', description)] : []),
  ];
  if (main) {
    lines.push(
      m('property', 'og:image', base + main.file),
      m('property', 'og:image:width', String(main.w)),
      m('property', 'og:image:height', String(main.h)),
      m('property', 'og:image:alt', alt),
      m('name', 'twitter:card', main.key === 'og' ? 'summary_large_image' : 'summary'),
      m('name', 'twitter:title', title),
      ...(description ? [m('name', 'twitter:description', description)] : []),
      m('name', 'twitter:image', base + main.file),
      m('name', 'twitter:image:alt', alt),
    );
  }
  if (pin) {
    lines.push('', '<!-- Pinterest reads its image off the page: add this attribute to the page\'s main <img> -->',
      `<!-- data-pin-media="${esc(base + pin.file)}" -->`);
  }
  return lines.join('\n');
}
