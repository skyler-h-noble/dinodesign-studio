const esc = (s: string) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** The brand in a link to the home page: logo, mark, or the logo that becomes
 *  the mark on a phone. role="img" + aria-label give the mask an accessible
 *  name — the brand's own, not "logo". */
export function brandHTML(meta: BrandMeta, urls: { logo?: string; stacked?: string; mark?: string }, opts: { show: BrandSlot | 'responsive'; height?: number; href?: string } = { show: 'responsive' }): string {
  const name = meta.name || 'Home';
  const h = opts.height || 32;
  const one = (slot: BrandSlot, extra: string) => {
    const s = meta[slot]; const url = urls[slot];
    if (!s || !url) return '';
    return `<span class="omni-brand omni-brand--${slot}${extra}" role="img" aria-label="${esc(name)}" style="--omni-brand-src: url('${url}'); --omni-brand-aspect: ${Math.round(s.aspect * 1000) / 1000}; --omni-brand-height: ${h}px${meta.color !== 'brand' ? `; --omni-brand-color: ${BRAND_COLOR_TOKEN[meta.color]}` : ''}"></span>`;
  };
  const inner = opts.show === 'responsive'
    ? [one('logo', ' omni-brand--responsive'), one('mark', ' omni-brand--responsive')].filter(Boolean).join('\n  ')
    : one(opts.show, '');
  return `<a class="omni-brand-link" href="${esc(opts.href || '/')}">\n  ${inner}\n</a>`;
}

