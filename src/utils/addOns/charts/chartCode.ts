/** A px number written without float noise (100.00000000001 → 100). */
const px = (n: number) => `${Math.round(n * 100) / 100}px`;

function slug(name: string): string {
  return (name || 'chart').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'chart';
}

