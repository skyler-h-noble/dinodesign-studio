/** The headline's inner HTML: consecutive Alt words share one span, which
 *  takes the Alt face but keeps the headline's size and leading — the pair
 *  share a baseline by design. */
export function headlineHTML(spec: HeroSpec): string {
  const words = headlineWords(spec.text.headline);
  // Over a gradient only — over a photo the headline is one face.
  const alt = new Set(spec.mode === 'gradient' ? spec.text.altWords : []);
  if (!alt.size) return esc(spec.text.headline);
  const a = altStyleFor(spec.text.headlineStyle);
  const color = spec.mode === 'gradient' && spec.text.altColor === 'alt' ? '; color: var(--Alt-Display-Color)' : '';
  const style = `font-family: var(--${a}-Font-Family); font-weight: var(--${a}-Font-Weight); letter-spacing: var(--${a}-Letter-Spacing); text-transform: var(--${a}-Text-Transform, none)${color}`;
  const out: string[] = [];
  let run: string[] = [];
  const flush = () => { if (run.length) out.push(`<span class="omni-hero__alt" style="${style}">${run.map(esc).join(' ')}</span>`); run = []; };
  words.forEach((w, i) => { if (alt.has(i)) run.push(w); else { flush(); out.push(esc(w)); } });
  flush();
  return out.join(' ');
}

/** Where the overlay is strongest: at the text's edge of the hero. */
export function overlayDirection(v: string, h: string): string | null {
  if (v === 'bottom') return 'to top';
  if (v === 'top') return 'to bottom';
  if (h === 'left') return 'to right';
  if (h === 'right') return 'to left';
  return null;
}

/** The hero's background CSS. */
export function heroBackground(spec: HeroSpec): string {
  if (spec.mode === 'gradient' && spec.gradient.variant === 'mesh') return meshBackground(spec);
  if (spec.mode === 'gradient') {
    const stops = [...spec.gradient.stops].sort((a, b) => a.pos - b.pos)
      .map((s) => `${toneToken(s.family, s.tone)} ${Math.round(s.pos * 100)}%`).join(', ');
    return spec.gradient.variant === 'radial'
      ? `radial-gradient(circle at 30% 30%, ${stops})`
      : `linear-gradient(${Math.round(spec.gradient.angle)}deg, ${stops})`;
  }
  return '';
}

/** A mesh: the first stop is the ground, every later one a soft blob fading
 *  to transparent, later stops on top. Each blob is an ellipse sized as a
 *  fraction of the hero's width and height, so the mesh keeps its layout on
 *  every device — and heroContrast samples exactly this composite. */
export function meshBackground(spec: HeroSpec): string {
  const [ground, ...blobs] = spec.gradient.stops;
  const layers = [...blobs].reverse().map((b) => {
    const r = Math.round(b.spread * 100);
    return `radial-gradient(ellipse ${r}% ${r}% at ${Math.round(b.x * 100)}% ${Math.round(b.y * 100)}%, ${toneToken(b.family, b.tone)} 0%, transparent 100%)`;
  });
  return [...layers, toneToken(ground.family, ground.tone)].join(', ');
}

/** The actions row's colors: the surface's Buttons tokens over a gradient, or
 *  the solved BW over a photo (where they sit inside the text box the overlay
 *  was solved for, so they clear the same ratio as the text). */
function buttonVars(spec: HeroSpec): string {
  if ((spec.mode === 'gradient' && !spec.gradient.bwRoles.includes('buttons')) || (imageThemed(spec) && !spec.image.bwRoles.includes('buttons'))) {
    // The palette the studio found working on this surface.
    const P = spec.mode === 'gradient' ? spec.gradient.buttonPalette : spec.image.buttonPalette;
    return [
      `--omni-hero-btn: var(--Buttons-${P}-Button)`,
      `--omni-hero-btn-text: var(--Buttons-${P}-Text)`,
      `--omni-hero-btn-border: var(--Buttons-${P}-Border, var(--Buttons-${P}-Button))`,
      `--omni-hero-btn-hover: var(--Buttons-${P}-Hover)`,
      `--omni-hero-btn-pressed: var(--Buttons-${P}-Pressed)`,
      `--omni-hero-btn-outline-text: var(--Buttons-${P}-Outline-Text)`,
      `--omni-hero-btn-outline-hover: var(--Hover)`,
    ].join('; ');
  }
  const on = BW[heroTextColor(spec)];
  const off = BW[heroTextColor(spec) === 'light' ? 'dark' : 'light'];
  return [
    `--omni-hero-btn: ${on}`,
    `--omni-hero-btn-text: ${off}`,
    `--omni-hero-btn-border: ${on}`,
    `--omni-hero-btn-hover: color-mix(in srgb, ${on} 85%, ${off})`,
    `--omni-hero-btn-pressed: color-mix(in srgb, ${on} 75%, ${off})`,
    `--omni-hero-btn-outline-text: ${on}`,
    `--omni-hero-btn-outline-hover: color-mix(in srgb, ${on} 15%, transparent)`,
  ].join('; ');
}

/** Over a photo, whether the text wears a system surface (else BW throughout). */
const imageThemed = (spec: HeroSpec) => spec.mode === 'image' && !!spec.image.surface;

/** A role's color over a themed photo: the surface's token, or the solved BW
 *  for a role whose token could not clear the photo. null when not themed. */
function roleColor(spec: HeroSpec, role: HeroRole, token: string): string | null {
  if (spec.mode === 'gradient') return spec.gradient.bwRoles.includes(role) ? BW[heroTextColor(spec)] : token;
  if (!imageThemed(spec)) return null;
  return spec.image.bwRoles.includes(role) ? BW[heroTextColor(spec)] : token;
}

/** The overlay between photo and text, as CSS. */
export function heroOverlay(spec: HeroSpec): string {
  // The overlay is the opposite of the text: dark behind light text — black or
  // white, or the chosen family at the tone the studio picked for that side.
  const color = spec.image.overlayFamily === 'BW' || !spec.image.overlayTone
    ? (spec.image.solvedText === 'light' ? BW.dark : BW.light)
    : toneToken(spec.image.overlayFamily, spec.image.overlayTone);
  const pct = Math.round(spec.image.alpha * 100);
  const mix = `color-mix(in srgb, ${color} ${pct}%, transparent)`;
  const dir = spec.image.overlay === 'gradient' ? overlayDirection(spec.text.v, spec.text.h) : null;
  return dir ? `linear-gradient(${dir}, ${mix} 0%, transparent 100%)` : mix;
}

/** The headline's color, exactly as heroHTML paints it — the surface's
 *  Header, the solved BW where that role fell back, or the hero's text color.
 *  A logo set beside the headline takes this, so the contrast solved for the
 *  headline covers the logo too. */
export function heroHeadlineColor(spec: HeroSpec): string {
  return roleColor(spec, 'headline', 'var(--Header)') || BW[heroTextColor(spec)];
}

export function heroTextColor(spec: HeroSpec): 'light' | 'dark' {
  return spec.mode === 'gradient'
    ? (spec.gradient.stops[0].tone <= 5 ? 'light' : 'dark')
    : spec.image.solvedText;
}

/**
 * The hero's HTML. `imageSrc` is the photo for the preview; the exported code
 * leaves a placeholder for the user's own file.
 */
export function heroHTML(spec: HeroSpec, imageSrc = 'your-image.jpg'): string {
  const just = { left: 'flex-start', center: 'center', right: 'flex-end' }[spec.text.h];
  const align = { top: 'flex-start', center: 'center', bottom: 'flex-end' }[spec.text.v];
  /* Full width always. A ratio keeps the shape and, being aspect-ratio with
     min-height: auto, still grows when the text needs more room. */
  const size = spec.heightMode === 'screen' ? 'width: 100%; min-height: 100svh'
    : spec.heightMode === 'ratio' ? `width: 100%; aspect-ratio: ${spec.ratio.replace(':', ' / ')}`
    : `width: 100%; min-height: ${Math.round(spec.height)}px`;
  const bg = heroBackground(spec);
  /* Over a gradient the hero IS a themed surface: data-theme + data-surface
     give it the system's own Header, Text and Eyebrow for that tone. Over a
     photo the text is the BW color the overlay was solved for. */
  /* Over a gradient the hero IS a themed surface; over a photo it wears one
     when the studio found a surface whose colors clear the photo — either way
     data-theme + data-surface give the system's own Header, Text, Eyebrow and
     buttons. Untheme'd, the text is the BW the overlay was solved for. */
  const themed = spec.mode === 'gradient' || imageThemed(spec);
  const text = roleColor(spec, 'body', 'var(--Text)') || BW[heroTextColor(spec)];
  const surfaceAttrs = spec.mode === 'gradient'
    ? ` data-theme="${spec.gradient.stops[0].family}" data-surface="${spec.gradient.surface}"`
    : imageThemed(spec) ? ` data-theme="${spec.image.theme}" data-surface="${spec.image.surface}"` : '';
  const eyebrowColor = roleColor(spec, 'eyebrow', 'var(--Eyebrow)');
  const headerColor = roleColor(spec, 'headline', 'var(--Header)');
  const t = spec.text;
  const parts: string[] = [];
  if (spec.mode === 'image') {
    const pos = `${spec.image.alignX} ${spec.image.alignY}`.replace('center center', 'center');
    // Decorative: the words are in the text. Give it alt text if the photo itself carries meaning.
    parts.push(`<img class="omni-hero__img" src="${esc(imageSrc)}" alt="" style="object-position: ${pos}">`);
    parts.push(`<div class="omni-hero__overlay" style="background: ${heroOverlay(spec)}" aria-hidden="true"></div>`);
  }
  const content = [
    t.eyebrow ? `<p class="omni-hero__eyebrow" style="font-size: var(--${t.eyebrowStyle}-Font-Size); letter-spacing: var(--${t.eyebrowStyle}-Letter-Spacing)${eyebrowColor ? `; color: ${eyebrowColor}` : ''}">${esc(t.eyebrow)}</p>` : '',
    t.headline ? `<h1 class="omni-hero__headline" style="${typeStyle(t.headlineStyle)}${headerColor ? `; color: ${headerColor}` : ''}">${headlineHTML(spec)}</h1>` : '',
    t.body ? `<p class="omni-hero__body" style="${typeStyle(t.bodyStyle)}">${esc(t.body)}</p>` : '',
    t.primaryAction || t.secondaryAction ? `<div class="omni-hero__actions" style="${buttonVars(spec)}; justify-content: ${just}">`
      + (t.primaryAction ? `\n      <a class="omni-hero__button" href="#">${esc(t.primaryAction)}</a>` : '')
      + (t.secondaryAction ? `\n      <a class="omni-hero__button omni-hero__button--outline" href="#">${esc(t.secondaryAction)}</a>` : '')
      + '\n    </div>' : '',
  ].filter(Boolean).join('\n    ');
  parts.push(`<div class="omni-hero__content" style="align-items: ${just}; text-align: ${t.h}">\n    ${content}\n  </div>`);
  return `<section class="omni-hero"${surfaceAttrs} data-omni-hero="${esc(JSON.stringify(spec))}" style="${size}; padding: var(--Margin, var(--omni-hero-margin)); justify-content: ${just}; align-items: ${align}; color: ${text};${bg ? ` background: ${bg};` : ''}">\n  `
    + parts.join('\n  ') + `\n</section>`;
}
