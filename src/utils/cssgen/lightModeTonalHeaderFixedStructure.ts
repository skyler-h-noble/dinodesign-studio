/**
 * Container tokens, derived from the Surfaces table.
 *
 * Containers no longer vary with the background tone — in light mode every container is flat at Color-11
 * regardless of background (elevation comes from drop shadows, not tone).
 * Every index therefore resolves to the Surfaces entry for Color-11, the
 * correct pairing for that container colour. Deriving rather than hand-
 * maintaining a second table means the two cannot drift apart.
 */
function containersFromSurfaces<T extends Record<string, Record<string, unknown>>>(
  surfaces: T,
  anchorFor: string | ((key: string) => string),
): T {
  const resolveAnchor = typeof anchorFor === 'function' ? anchorFor : () => anchorFor;
  const out: Record<string, Record<string, unknown>> = {};
  for (const palette of Object.keys(surfaces)) {
    out[palette] = {};
    for (const key of Object.keys(surfaces[palette])) {
      out[palette][key] = surfaces[palette][resolveAnchor(key)];
    }
  }
  return out as T;
}

/**
 * Light-mode container anchor. Index N is the BACKGROUND tone the theme sits
 * on; the container it produces is Color-11 on a light background (tones 6-12)
 * and Color-2 on a dark one (tones 1-5, e.g. the Black theme). Pick the
 * Surfaces entry for whichever tone the container actually renders at.
 */
const lightContainerAnchor = (key: string): string => {
  const n = parseInt(key.replace('Color-', ''), 10);
  return Number.isFinite(n) && n <= 5 ? 'Color-2' : 'Color-11';
};

export const lightModeTonalHeaderFixed = {
  Surfaces: lightModeTonalHeaderSurfaces,
  Containers: containersFromSurfaces(lightModeTonalHeaderSurfaces, lightContainerAnchor),
};


