/**
 * The bento as HTML + CSS on the user's design system.
 *
 * A CSS grid on the layout tokens: --Columns columns, --Gutter gaps, --Margin
 * at the sides — set per data-device by the system's CSS, so the grid has 12
 * columns on desktop, 8 on a tablet and 4 on a phone without a breakpoint of
 * its own. Each tile carries its three spans as custom properties and the
 * stylesheet picks one by device. Colors and type are the tile's surface's own
 * tokens; only geometry is literal.
 *
 * Two styles: Cards (the grid's gutter and margin, each tile a card) and
 * Boxes (.omni-bento--boxes: flush, the surfaces doing the separating).
 *
 * Systems published before --Columns existed fall back to the same numbers by
 * screen width, the way the hero's --Margin does.
 */
import { bentoSpan, bentoRows, type BentoSpec, type BentoTile } from './bentoSpec';

const esc = (s: string) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const TABLET = ':is([data-device="IOS-Tablet"], [data-device="Android-Tablet"])';
const PHONE = ':is([data-device="IOS-Mobile"], [data-device="Android-Mobile"], [data-device="Android"])';

export function bentoCSS(): string {
  return `/* Omni bento — generated by the Bento Grid add-on. The grid follows your
   design system's --Columns / --Gutter / --Margin per device; the tiles wear
   your surfaces, so their text is the surface's own accessible colors. */
:root { --omni-bento-columns: 12; --omni-bento-gutter: 32px; --omni-bento-margin: 64px; }
@media (max-width: 1023px) { :root { --omni-bento-columns: 8; --omni-bento-gutter: 24px; --omni-bento-margin: 24px; } }
@media (max-width: 599px) { :root { --omni-bento-columns: 4; --omni-bento-gutter: 16px; --omni-bento-margin: 16px; } }
.omni-bento {
  display: grid; box-sizing: border-box; width: 100%; margin: 0;
  grid-template-columns: repeat(var(--Columns, var(--omni-bento-columns)), minmax(0, 1fr));
  grid-auto-rows: minmax(var(--omni-bento-row, 200px), auto);
  gap: var(--Gutter, var(--omni-bento-gutter));
  /* The device margin on every side, as the hero takes it: a bento is a page
     section, and its tiles should not touch the sections above and below. */
  padding: var(--Margin, var(--omni-bento-margin));
}
.omni-bento *, .omni-bento *::before, .omni-bento *::after { box-sizing: border-box; }
.omni-bento__tile {
  grid-column: span var(--span); grid-row: span var(--rows);
  display: flex; flex-direction: column; gap: var(--Sizing-1, 8px); min-width: 0; overflow: hidden;
  padding: var(--Card-Padding, 24px); border-radius: var(--Card-Radius, 16px);
  background: var(--Background); color: var(--Text);
  /* The Card's edge: Border-Variant on Surface-Brightest, transparent elsewhere. */
  border: 1px solid var(--Card-Border, transparent);
}
/* A tablet is 8 columns held upright and 12 on its side (Figma's
   IOS-Tablet-Horizontal), but CSS has one data-device per tablet. A page can
   say which with data-orientation; without it, the screen's orientation does. */
${TABLET}[data-orientation="portrait"] .omni-bento__tile { grid-column: span var(--span-t); }
@media (orientation: portrait) { ${TABLET}:not([data-orientation]) .omni-bento__tile { grid-column: span var(--span-t); } }
${TABLET}[data-orientation="landscape"] .omni-bento { --Columns: 12; }
@media (orientation: landscape) { ${TABLET}:not([data-orientation]) .omni-bento { --Columns: 12; } }
${PHONE} .omni-bento__tile { grid-column: span var(--span-m); grid-row: span var(--rows-m); }
/* No data-device on the page: the same spans by screen width. */
@media (max-width: 1023px) { .omni-bento__tile:not([data-device] *) { grid-column: span var(--span-t); } }
@media (max-width: 599px) { .omni-bento__tile:not([data-device] *) { grid-column: span var(--span-m); grid-row: span var(--rows-m); } }
.omni-bento__tile > * { margin: 0; }
.omni-bento__eyebrow {
  color: var(--Eyebrow, var(--Text)); text-transform: uppercase;
  font-family: var(--Font-Family-Eyebrow, var(--Body-Font-Family));
  font-weight: var(--Font-Weight-Eyebrow, 600);
  font-size: var(--Eyebrow-Small-Font-Size); letter-spacing: var(--Eyebrow-Small-Letter-Spacing);
}
.omni-bento__title {
  color: var(--Header); font-family: var(--H4-Font-Family); font-size: var(--H4-Font-Size);
  font-weight: var(--H4-Font-Weight); line-height: var(--H4-Line-Height); letter-spacing: var(--H4-Letter-Spacing);
}
.omni-bento__body {
  font-family: var(--Body-Medium-Font-Family); font-size: var(--Body-Medium-Font-Size);
  line-height: var(--Body-Medium-Line-Height); max-width: 60ch;
}
.omni-bento__stat {
  color: var(--Header); font-family: var(--Display-Small-Font-Family); font-size: var(--Display-Small-Font-Size);
  font-weight: var(--Display-Small-Font-Weight); line-height: var(--Display-Small-Line-Height);
}
.omni-bento__link {
  margin-top: auto; align-self: flex-start; color: var(--Hotlink); text-decoration: underline;
  font-family: var(--Font-Family-Button, var(--Body-Font-Family)); font-weight: var(--Button-Font-Weight, 600);
}
.omni-bento__link:hover { text-decoration-thickness: 2px; }
.omni-bento__link:focus-visible { outline: 3px solid var(--Focus-Visible, currentColor); outline-offset: 2px; }
/* Boxes: flush tiles — no gutter, no margin, square, no edge. The surfaces
   alone tell one tile from the next. The padding inside stays, so text never
   meets an edge. */
.omni-bento--boxes { gap: 0; padding: 0; }
.omni-bento--boxes > .omni-bento__tile { border-radius: 0; border: 0; }
.omni-bento__tile--stat { justify-content: flex-end; }
.omni-bento__tile--image { padding: 0; }
.omni-bento__img { width: 100%; height: 100%; object-fit: cover; display: block; }`;
}

function tileHTML(t: BentoTile, imageSrc: string, n?: number): string {
  const vars = `--span: ${bentoSpan(t, 'desktop')}; --span-t: ${bentoSpan(t, 'tablet')}; --span-m: ${bentoSpan(t, 'mobile')}; --rows: ${bentoRows(t, 'desktop')}; --rows-m: ${bentoRows(t, 'mobile')}`;
  // data-tile only in the studio's preview copy — it labels the tile on hover.
  const attrs = `class="omni-bento__tile omni-bento__tile--${t.kind}" data-theme="${t.theme}" data-surface="${t.surface}" style="${vars}"${n ? ` data-tile="${n}"` : ''}`;
  if (t.kind === 'image') {
    // Decorative unless described: the alt says so either way.
    return `<div ${attrs}><img class="omni-bento__img" src="${esc(imageSrc)}" alt="${esc(t.alt)}"></div>`;
  }
  const parts: string[] = [];
  if (t.kind === 'stat') {
    if (t.stat) parts.push(`<p class="omni-bento__stat">${esc(t.stat)}</p>`);
    if (t.statLabel) parts.push(`<p class="omni-bento__body">${esc(t.statLabel)}</p>`);
  } else {
    if (t.eyebrow) parts.push(`<p class="omni-bento__eyebrow">${esc(t.eyebrow)}</p>`);
    if (t.title) parts.push(`<h3 class="omni-bento__title">${esc(t.title)}</h3>`);
    if (t.body) parts.push(`<p class="omni-bento__body">${esc(t.body)}</p>`);
    if (t.action) parts.push(`<a class="omni-bento__link" href="#">${esc(t.action)}</a>`);
  }
  return `<div ${attrs}>\n    ${parts.join('\n    ')}\n  </div>`;
}

/** The bento's HTML. `imageSrc` fills image tiles in the preview; the export
 *  leaves a placeholder for the user's own file. The spec rides on the
 *  section, so pasting the HTML back reopens it for editing. */
export function bentoHTML(spec: BentoSpec, imageSrc = 'your-image.jpg', opts: { preview?: boolean } = {}): string {
  const cls = spec.style === 'boxes' ? 'omni-bento omni-bento--boxes' : 'omni-bento';
  return `<section class="${cls}" style="--omni-bento-row: ${spec.rowHeight}px" aria-label="${esc(spec.name)}" data-omni-bento="${esc(JSON.stringify(spec))}">\n  `
    + spec.tiles.map((t, i) => tileHTML(t, imageSrc, opts.preview ? i + 1 : undefined)).join('\n  ')
    + '\n</section>';
}
