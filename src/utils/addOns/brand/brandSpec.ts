/**
 * Brand — the user's logo (with words) and mark (without), stored once per
 * design system and drawn everywhere in ONE color that adapts to its surface.
 *
 * ── One color, from the surface ───────────────────────────────────────────
 * Every mark is an "ink" SVG: a single shape filled with currentColor, on
 * nothing. Code draws it as a CSS mask over the surface's own brand color —
 * --Header-Primary, which every surface already tunes to 3:1, the contrast
 * WCAG asks of a graphic — so the same file reads on a light card, a dark
 * hero and in dark mode with no per-surface work. A mask never runs what is
 * inside the file, so an uploaded SVG is safe to use this way. Figma gets the
 * same shape as vectors with their fill bound to Surface/Header-Primary.
 *
 * ── Favicons and app icons ────────────────────────────────────────────────
 * The mark on a tile in the brand's button color, in that button's label
 * color — a pair the system already makes pass — at the sizes browsers and
 * phones ask for.
 */

export const BRAND_SPEC_VERSION = 'brand1';

/** Where a design system's brand lives in Storage, under design-systems/{uuid}/. */
export const BRAND_FILES = {
  meta: 'brand/brand.json',
  logo: 'brand/logo.svg',
  stacked: 'brand/stacked.svg',
  mark: 'brand/mark.svg',
} as const;

/** The three shapes a brand comes in: the full logo (wide), the stacked
 *  logo (compact — for square-ish spaces), and the mark (the symbol alone). */
export type BrandSlot = 'logo' | 'stacked' | 'mark';
export const BRAND_SLOTS: BrandSlot[] = ['logo', 'stacked', 'mark'];

/** Which surface color the brand takes:
 *    brand    each surface's Header-Primary — the brand color, tuned to 3:1 on every surface
 *    neutral  each surface's Header
 *    bw       each surface's Text-BW — black on light surfaces, white on dark: the most contrast there is */
export type BrandColor = 'brand' | 'neutral' | 'bw';
export const BRAND_COLOR_TOKEN: Record<BrandColor, string> = {
  brand: 'var(--Header-Primary, var(--Header))',
  neutral: 'var(--Header)',
  bw: 'var(--Text-BW, var(--Header))',
};
/** The Figma Surface variable each color binds to. */
export const BRAND_COLOR_VARIABLE: Record<BrandColor, string> = { brand: 'Header-Primary', neutral: 'Header', bw: 'Text-BW' };

export interface BrandMeta {
  version: string;
  /** The site or company name: the brand's accessible name, and the app's name in its manifest. */
  name: string;
  color: BrandColor;
  /** Width ÷ height of each ink SVG, or null when that slot is empty. */
  logo: { aspect: number } | null;
  stacked: { aspect: number } | null;
  mark: { aspect: number } | null;
  updated: string;
}

export function normalizeBrandMeta(raw: unknown): BrandMeta {
  const r = (raw && typeof raw === 'object' ? raw : {}) as Record<string, any>;
  const slot = (v: any) => (v && typeof v === 'object' && Number(v.aspect) > 0 ? { aspect: Number(v.aspect) } : null);
  return {
    version: BRAND_SPEC_VERSION,
    name: typeof r.name === 'string' ? r.name.slice(0, 60) : '',
    color: r.color === 'neutral' || r.color === 'bw' ? r.color : 'brand',
    logo: slot(r.logo),
    stacked: slot(r.stacked),
    mark: slot(r.mark),
    updated: typeof r.updated === 'string' ? r.updated : '',
  };
}

/* ── SVG strings ────────────────────────────────────────────────────────── */

/** The viewBox of an SVG string, falling back to its width / height. */
export function svgViewBox(svg: string): { x: number; y: number; w: number; h: number } | null {
  const vb = svg.match(/viewBox\s*=\s*["']\s*([-\d.eE]+)[\s,]+([-\d.eE]+)[\s,]+([-\d.eE]+)[\s,]+([-\d.eE]+)\s*["']/);
  if (vb) return { x: +vb[1], y: +vb[2], w: +vb[3], h: +vb[4] };
  const w = svg.match(/<svg[^>]*\swidth\s*=\s*["']([\d.]+)/); const h = svg.match(/<svg[^>]*\sheight\s*=\s*["']([\d.]+)/);
  return w && h ? { x: 0, y: 0, w: +w[1], h: +h[1] } : null;
}

/** An ink SVG in one literal color — for a PNG, where there is no currentColor to inherit. */
export function inkInColor(svg: string, color: string): string {
  return svg.replace(/currentColor/g, color);
}

export const svgDataUrl = (svg: string) => `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;

